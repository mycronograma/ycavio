export function findSuggestedTopicsForSubject(subjectName: string): string[] {
  const direct = PRESET_SUBJECT_TOPICS[subjectName];
  if (direct) return [...direct];

  const normalizedInput = normalizeText(subjectName);
  if (!normalizedInput) return [];

  for (const [key, topics] of Object.entries(PRESET_SUBJECT_TOPICS)) {
    const normalizedKey = normalizeText(key);
    if (normalizedKey === normalizedInput) {
      return [...topics];
    }
  }

  for (const alias of ALIAS_MAP) {
    if (alias.keywords.some((kw) => normalizedInput.includes(kw))) {
      return [...(PRESET_SUBJECT_TOPICS[alias.target] || [])];
    }
  }

  for (const [key, topics] of Object.entries(PRESET_SUBJECT_TOPICS)) {
    const normalizedKey = normalizeText(key);
    if (normalizedInput.length >= 4 && (normalizedKey.includes(normalizedInput) || normalizedInput.includes(normalizedKey))) {
      return [...topics];
    }
  }

  return [];
}
